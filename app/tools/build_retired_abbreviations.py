"""Writes lib/retired_abbreviations.dart: the five-letter words (a daily is five
letters) that the English Wiktionary shows as nothing but an abbreviation, for
every language, from the output of wikt_abbreviations.py.

    python wikt_abbreviations.py          (streams the dumps, 20-30 minutes)
    python build_retired_abbreviations.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "wikt_abbr_out"
DART = HERE.parent / "lib" / "retired_abbreviations.dart"
LENGTH = 5


def main():
    manifest = json.loads((HERE.parent / "assets" / "words" / "languages.json").read_text(encoding="utf-8"))
    lines = [
        "// GENERATED by tools/build_retired_abbreviations.py from the English",
        "// Wiktionary (see tools/wikt_abbreviations.py): do not edit by hand.",
        "",
        "/// The five-letter words of each language whose Wiktionary entry shows an",
        "/// abbreviation, an initialism or an acronym and nothing else. They stay valid",
        "/// guesses; from `dailyRetireFromLater` no daily answer is one of them.",
        "const retiredAbbreviations = <String, Set<String>>{",
    ]
    total = 0
    for e in manifest:
        f = OUT / f"abbr-{e['code']}.json"
        if not f.exists():
            continue
        d = json.loads(f.read_text(encoding="utf-8"))
        words = sorted(w for w, r in d.items() if r["kind"] in ("pure", "caps") and len(w) == LENGTH)
        total += len(words)
        lines.append(f"  '{e['code']}': {{")
        row = "   "
        for w in words:
            item = f" '{w}',"
            if len(row) + len(item) > 78:
                lines.append(row)
                row = "   "
            row += item
        lines.append(row + " //")
        lines.append("  },")
    lines.append("};")
    DART.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("words:", total)


if __name__ == "__main__":
    main()
