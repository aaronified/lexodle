"""Writes lib/retired_abbreviations.dart: the words that the English Wiktionary
shows as nothing but an abbreviation, an initialism or an acronym, for every
language, from the output of wikt_abbreviations.py. A word that is a clipping
of a longer word (condo, corgi) is not one: it is kept.

    python wikt_abbreviations.py          (streams the dumps, 20-30 minutes)
    python build_retired_abbreviations.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "wikt_abbr_out"
DART = HERE.parent / "lib" / "retired_abbreviations.dart"
# a shortening of a longer word that is a word itself (condo, queso, minke) is kept
CLIPPING = {"clipping", "ellipsis"}


def retired(r):
    if r["kind"] not in ("pure", "caps"):
        return False
    if not set(r["why"]) - {"head"}:
        return False
    sets = r.get("tagsets") or []
    # every abbreviation sense is also a clipping: a word shortened from another
    if sets and all(CLIPPING & set(t) for t in sets):
        return False
    return True


def main():
    manifest = json.loads((HERE.parent / "assets" / "words" / "languages.json").read_text(encoding="utf-8"))
    lines = [
        "// GENERATED by tools/build_retired_abbreviations.py from the English",
        "// Wiktionary (see tools/wikt_abbreviations.py): do not edit by hand.",
        "",
        "/// The words of each language whose Wiktionary entry shows an abbreviation, an",
        "/// initialism or an acronym and nothing else (not a clipping of a longer word,",
        "/// like condo). From `dailyRetireFromLater` they are no guesses, no free play",
        "/// answers and no daily answers.",
        "const retiredAbbreviations = <String, Set<String>>{",
    ]
    total = 0
    for e in manifest:
        f = OUT / f"abbr-{e['code']}.json"
        if not f.exists():
            continue
        d = json.loads(f.read_text(encoding="utf-8"))
        # (an entry whose only mention is in its heading line, like the Polish
        # aleja, "abbreviation: al.", is not an abbreviation: "head" does not count)
        words = sorted(w for w, r in d.items() if retired(r))
        total += len(words)
        lines.append(f"  '{e['code']}': {{")
        row = "   "
        for w in words:
            item = f" '{w}',"
            if len(row) + len(item) > 78:
                lines.append(row)
                row = "   "
            row += item
        lines.append(row + " //")
        lines.append("  },")
    lines.append("};")
    DART.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("words:", total)


if __name__ == "__main__":
    main()
